import asyncio
import json
import time
from datetime import UTC, datetime
from pathlib import Path
from urllib.parse import quote, urlencode

from app.core.errors import AppError
from app.core.security import sign, signature_valid
from app.providers.storage.base import ObjectInfo, PresignedUpload


class LocalDiskStorage:
    """Files under one directory, so nothing needs a cloud account.

    S3 would let the client upload straight to the bucket with a presigned POST. To keep the same
    flow, this provider "presigns" with an HMAC: the URL points to this app's own /storage/upload
    endpoint, and the signed fields fix the key, content type, size limit and expiry, as an S3
    POST policy would. Downloads work the same way with /storage/files/{key}.
    """

    name = "local"

    def __init__(self, root: str, public_base_url: str, signing_secret: str) -> None:
        self._root = Path(root).resolve()
        self._base_url = public_base_url.rstrip("/")
        self._secret = signing_secret

    def _path(self, key: str) -> Path:
        path = (self._root / key).resolve()
        # Keys are generated by the app, but never let one escape the storage root.
        if not path.is_relative_to(self._root):
            raise ValueError(f"Storage key escapes the storage root: {key}")
        return path

    def presign_upload(
        self, key: str, content_type: str, max_bytes: int, expires_in: int
    ) -> PresignedUpload:
        expires = int(time.time()) + expires_in
        fields = {
            "key": key,
            "Content-Type": content_type,
            "maxBytes": str(max_bytes),
            "expires": str(expires),
            "signature": sign(self._secret, "upload", key, content_type, max_bytes, expires),
        }
        return PresignedUpload(
            url=f"{self._base_url}/storage/upload",
            fields=fields,
            expires_at=datetime.fromtimestamp(expires, UTC),
        )

    def presign_download(self, key: str, expires_in: int) -> str:
        expires = int(time.time()) + expires_in
        query = urlencode(
            {"expires": expires, "signature": sign(self._secret, "download", key, expires)}
        )
        return f"{self._base_url}/storage/files/{quote(key)}?{query}"

    def check_upload(self, fields: dict[str, str]) -> tuple[str, str, int]:
        """Validates a form upload's signed fields. Returns (key, content type, max bytes)."""
        try:
            key, content_type = fields["key"], fields["Content-Type"]
            max_bytes, expires = int(fields["maxBytes"]), int(fields["expires"])
            signature = fields["signature"]
        except (KeyError, ValueError) as exc:
            raise AppError(403, "INVALID_SIGNATURE", "Missing or malformed upload fields") from exc
        if not signature_valid(
            self._secret, signature, "upload", key, content_type, max_bytes, expires
        ):
            raise AppError(403, "INVALID_SIGNATURE", "Upload signature does not match")
        if time.time() > expires:
            raise AppError(403, "EXPIRED", "Upload URL has expired")
        return key, content_type, max_bytes

    def check_download(self, key: str, expires: int, signature: str) -> None:
        if not signature_valid(self._secret, signature, "download", key, expires):
            raise AppError(403, "INVALID_SIGNATURE", "Download signature does not match")
        if time.time() > expires:
            raise AppError(403, "EXPIRED", "Download URL has expired")

    async def head(self, key: str) -> ObjectInfo | None:
        path = self._path(key)
        if not await asyncio.to_thread(path.exists):
            return None
        meta = json.loads(await asyncio.to_thread(self._meta_path(path).read_text))
        size = (await asyncio.to_thread(path.stat)).st_size
        return ObjectInfo(size_bytes=size, content_type=meta["content_type"])

    async def get(self, key: str) -> bytes:
        return await asyncio.to_thread(self._path(key).read_bytes)

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        path = self._path(key)
        await asyncio.to_thread(path.parent.mkdir, parents=True, exist_ok=True)
        await asyncio.to_thread(path.write_bytes, data)
        meta = json.dumps({"content_type": content_type})
        await asyncio.to_thread(self._meta_path(path).write_text, meta)

    async def delete(self, key: str) -> None:
        path = self._path(key)
        await asyncio.to_thread(path.unlink, missing_ok=True)
        await asyncio.to_thread(self._meta_path(path).unlink, missing_ok=True)

    @staticmethod
    def _meta_path(path: Path) -> Path:
        """The content type, kept beside the file (S3 keeps it as object metadata)."""
        return path.with_name(path.name + ".meta.json")
